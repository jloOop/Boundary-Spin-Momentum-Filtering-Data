def sha(p: Path) -> str:
    h=hashlib.sha256()
    with p.open('rb') as f:
        for b in iter(lambda:f.read(1<<20),b''): h.update(b)
    return h.hexdigest()


def dump(p, obj):
    def clean(x):
        if isinstance(x,dict):return {str(k):clean(v) for k,v in x.items()}
        if isinstance(x,(list,tuple,np.ndarray)):return [clean(v) for v in x]
        if isinstance(x,np.generic):return clean(x.item())
        if isinstance(x,Path):return str(x)
        if isinstance(x,float) and not np.isfinite(x):return None
        return x
    p.write_text(json.dumps(clean(obj),indent=2,allow_nan=False)+'\n')


def require(c, msg):
    if not c: raise ValueError(msg)


def lin_cut(t,y,a,b):
    require(t[0]<=a+1e-12 and b<=t[-1]+1e-12 and b>a,'Unsupported linear integration interval')
    x=np.r_[a,t[(t>a)&(t<b)],b]
    v=np.interp(x,t,y)
    return x,v


def lin_mom(t,y,a,b):
    x,v=lin_cut(t,y,a,b); l=x[:-1];r=x[1:];h=r-l;u=v[:-1];w=v[1:]
    return float(np.sum(h*(u+w)/2)),float(np.sum(h*((2*l+r)*u+(l+2*r)*w)/6))


def abs_linear(x,v):
    h=np.diff(x);u=v[:-1];w=v[1:];area=h*(np.abs(u)+np.abs(w))/2
    cross=((u<0)&(w>0))|((u>0)&(w<0))
    area[cross]=h[cross]*(u[cross]**2+w[cross]**2)/(2*(abs(u[cross])+abs(w[cross])))
    return float(area.sum())


def event_mom(d,a,b,values=None):
    require(0<=a<b<=d['T']+1e-12,'Unsupported event integration interval')
    l=np.maximum(d['l'],a);r=np.minimum(d['r'],b);idx=r>l
    rate=(d['p'] if values is None else values)/d['dt_actual']
    return float(np.sum((r-l)[idx]*rate[idx])),float(np.sum((r-l)[idx]*(r+l)[idx]/2*rate[idx]))


def event_rate(d,t):
    return d['p'][np.searchsorted(d['r'],t,side='right')]/d['dt_actual'][np.searchsorted(d['r'],t,side='right')]


def spin_vec(E):
    tr=(E[0,0]+E[1,1]).real
    return np.array([2*E[0,1].real,-2*E[0,1].imag,(E[0,0]-E[1,1]).real])/tr


def avg_E2(d,a,b):
    g=d['diag'];t=g['time'];u=g['roof_density'];v=g['one_grid_E2br'];valid=g['one_grid_valid']
    l=np.maximum(t[:-1],a);r=np.minimum(t[1:],b)
    ok=(r>l)&valid[:-1]&valid[1:]&np.isfinite(v[:-1])&np.isfinite(v[1:])
    i=np.flatnonzero(ok);l=l[ok];r=r[ok];h=r-l
    f=(l-t[i])/(t[i+1]-t[i]);q=(r-t[i])/(t[i+1]-t[i])
    u0=u[i]+f*(u[i+1]-u[i]);u1=u[i]+q*(u[i+1]-u[i]);v0=v[i]+f*(v[i+1]-v[i]);v1=v[i]+q*(v[i+1]-v[i])
    den=np.sum(h*(u0+u1)/2)
    return float(np.sum(h*(2*u0*v0+u0*v1+u1*v0+2*u1*v1)/6)/den) if den else np.nan


def load_run(p, allow_live_prefix=False):
    m=json.loads((p/'revision_run.json').read_text());c=m['configuration'];P0=float(m['P0_init64'])
    f=pd.read_csv(p/'revision_step_data.csv',float_precision='round_trip')
    with np.load(p/'revision_spin_branch_diagnostics.npz',allow_pickle=False) as z: dg={k:z[k] for k in z.files}
    with np.load(p/'revision_coordinates.npz',allow_pickle=False) as z: co={k:z[k] for k in z.files}
    with np.load(p/'constants.npz',allow_pickle=False) as z: const={k:z[k] for k in z.files}
    name=int(p.name.split('.')[0]); T=float(m['actual_time'])
    is_final=m['status']=='COMPLETED_NUMERICAL_RUN_NOT_CONVERGENCE_CERTIFIED'
    is_live=m['status']=='RUNNING_NOT_VALIDATED'
    require(is_final or (allow_live_prefix and is_live), f'{name}: unsupported run status')
    # Validate every available CSV row, then use ONLY the shared metadata/diagnostic prefix.
    require(np.isfinite(f.to_numpy()).all(),f'{name}: nonfinite CSV entries')
    require(np.array_equal(f['step'],np.arange(1,len(f)+1)),f'{name}: full CSV step sequence invalid')
    require(np.array_equal(f.t_left.to_numpy()[1:], f.t_right.to_numpy()[:-1]), f'{name}: full CSV time chain invalid')
    require(np.array_equal(f.mass_before.to_numpy()[1:], f.mass_stored.to_numpy()[:-1]), f'{name}: full CSV mass chain invalid')
    available_rows=len(f); available_T=float(f.t_right.iloc[-1])
    if not is_final:
        n=int(m['completed_step'])
        require(len(f)>=n and int(dg['step'][-1])==n, f'{name}: no shared metadata/diagnostic prefix')
        f=f.iloc[:n].copy()
    
    require(np.array_equal(f['step'],np.arange(1,len(f)+1)),f'{name}: noncontiguous step numbers')
    require(len(f)==m['completed_step'],f'{name}: step count mismatch')
    l=f.t_left.to_numpy();r=f.t_right.to_numpy();h=r-l
    require(l[0]==0 and r[-1]==T and np.all(h>0),f'{name}: wrong time support')
    require(np.array_equal(l[1:],r[:-1]),f'{name}: time gap')
    require(np.array_equal(f.mass_before.to_numpy()[1:],f.mass_stored.to_numpy()[:-1]),f'{name}: broken mass chain')
    require(f.mass_before.iloc[0]==P0,f'{name}: launch mass mismatch')
    require(sha(p/'source_snapshot.py')==m['updated_source_sha256'],f'{name}: source hash mismatch')
    require(hashlib.sha256(json.dumps(c,sort_keys=True).encode()).hexdigest()==m['configuration_sha256'],f'{name}: configuration hash mismatch')
    require(np.array_equal(dg['time'],np.r_[0,r][dg['step']]),f'{name}: diagnostic time step mismatch')
    require(dg['time'][0]==0 and dg['time'][-1]==T and np.all(np.diff(dg['time'])>0),f'{name}: bad diagnostic grid')
    for k in ['Nx','Ny','Nz','omega','dt','T_final','hx','hy','hz','k0','k_bc','sigma_z','theta','phi']:
        require(float(const[k])==float(c[k]),f'{name}: constants mismatch {k}')
    d=dict(case=name,path=p,meta=m,cfg=c,P0=P0,f=f,diag=dg,coords=co,T=T,
           complete=is_final,available_rows=available_rows,available_T=available_T,
           l=l,r=r,dt_actual=h,p=f.roof_probability.to_numpy()/P0,
           t=np.r_[0,r],S=np.r_[P0,f.mass_stored.to_numpy()]/P0,ev=f[EVENT].to_numpy()/P0)
    return d


def quality(d):
    f=d['f'];P0=d['P0'];dg=d['diag'];n=len(f)
    corrections=f.solve_and_matrix_defect+f.cast_mass_loss+f.clamp_mass_loss
    budget=1-d['S'][1:]-np.cumsum(d['p']);corr=np.cumsum(corrections.to_numpy()/P0)
    up=f.p_spin_up.to_numpy();dn=f.p_spin_down.to_numpy();re=f.p_spin_offdiag_real.to_numpy();im=f.p_spin_offdiag_imag.to_numpy()
    tr=up+dn;gap=np.hypot(np.hypot(up-dn,2*re),2*im);e0=(tr-gap)/2
    dense_mass=np.r_[P0,f.mass_stored.to_numpy()]
    Pdet_nonzero=tr>0
    r=dict(case=d['case'],omega=d['cfg']['omega'],T=d['T'],n_steps=n,n_diagnostics=len(dg['time']),
        source_hash_verified=True,configuration_hash_verified=True,
        no_declared_restart=not any('resum' in k.lower() or 'restart' in k.lower() for k in d['meta']),
        max_true_relative_residual=float(f.relative_residual.max()),
        max_cumulative_detector_survival_gap=float(np.max(abs(budget))),final_detector_survival_gap=float(budget[-1]),
        max_unexplained_probability_budget=float(np.max(abs(budget-corr))),
        sum_solve_matrix_correction=float(f.solve_and_matrix_defect.sum()/P0),
        sum_cast_correction=float(f.cast_mass_loss.sum()/P0),sum_clamp_correction=float(f.clamp_mass_loss.sum()/P0),
        negative_detector_event_count=int((f.roof_probability<0).sum()),min_event_eigenvalue=float(e0.min()),
        max_event_Bloch_norm=float(np.max(gap[Pdet_nonzero]/tr[Pdet_nonzero])),
        max_event_trace_gap=float(np.max(abs(tr-f.roof_probability))),
        max_mass_chain_gap=float(np.max(abs(f.mass_before.to_numpy()[1:]-f.mass_stored.to_numpy()[:-1]))),
        positive_survival_increment_count=int((np.diff(d['S'])>0).sum()),max_survival_increase=float(max(0,np.diff(d['S']).max())),
        max_diagnostic_mass_gap=float(np.max(abs(dg['no_click_mass64']-dense_mass[dg['step']]))),
        max_survivor_trace_gap=float(np.max(abs(np.trace(dg['no_click_spin_matrix'],axis1=1,axis2=2).real-dg['no_click_mass64']))),
        max_roof_trace_gap=float(np.max(abs(np.trace(dg['roof_spin_matrix'],axis1=1,axis2=2).real-dg['roof_density']))),
        max_branch_partition_gap=float(np.max(abs(sum(dg[k] for k in BR)-dg['roof_density']))),
        P0=P0,z_detector=float(d['coords']['z'][-1]),
        actual_final_step=float(d['dt_actual'][-1]),
        record_cumulative_probability_gap=float(abs(f.roof_probability.sum()-d['meta']['cumulative_roof_probability'])),
        final_mass_record_gap=float(abs(f.mass_stored.iloc[-1]-d['meta']['current_accepted_prefix_mass64'])))
    if 'roof_cell_balance_defect' in f:
        cell=f.midpoint_interior_face_probability-f.roof_probability-f.roof_cell_mass_solved+f.roof_cell_mass_before
        r.update(max_cell_defect_reconstruction_gap=float(np.max(abs(cell-f.roof_cell_balance_defect))),
            max_single_cell_balance_defect=float(np.max(abs(cell))/P0),sum_cell_balance_signed=float(cell.sum()/P0),sum_cell_balance_abs=float(abs(cell).sum()/P0))
    pt=np.load(d['path']/'prob_times.npy');pv=np.load(d['path']/'total_probs.npy');ids=np.searchsorted(d['t'],pt)
    require(np.array_equal(pt,d['t'][ids]),'probability times not accepted-state times')
    r['max_native_vs_float64_mass_difference']=float(np.max(abs(pv-dense_mass[ids])))
    for field in ['roof_spin_matrix','no_click_spin_matrix']:
        mat=dg[field];eig=np.linalg.eigvalsh(mat)
        r['min_eigenvalue_'+field]=float(eig.min());r['max_hermiticity_gap_'+field]=float(np.max(abs(mat-np.swapaxes(mat.conj(),1,2))))
    return r


def window(d,a,b):
    D,M=event_mom(d,a,b);E=[event_mom(d,a,b,d['ev'][:,j])[0] for j in range(4)]
    P=np.array([2*E[2],-2*E[3],E[0]-E[1]])/(E[0]+E[1])
    dg=d['diag'];td=dg['time'];den,z1=lin_mom(td,dg['roof_density'],a,b)
    r2,_=lin_mom(td,dg['roof_R2_numerator'],a,b);ra,ra1=lin_mom(td,dg['roof_Ra_numerator'],a,b)
    lam=ra1/den-z1*ra/den**2
    out=dict(case=d['case'],omega=d['cfg']['omega'],a=a,b=b,D=D,M=M,tcond=M/D,
        Pxdet=P[0],Pydet=P[1],Pzdet=P[2],Dup=E[0],Ddown=E[1],
        wplus=lin_mom(td,dg[BR[0]],a,b)[0]/den,wminus=lin_mom(td,dg[BR[1]],a,b)[0]/den,
        wneutral=lin_mom(td,dg[BR[2]],a,b)[0]/den,Es2=r2/den/d['cfg']['omega'],beta=lam/np.sqrt(d['cfg']['omega']),Lambda=lam,
        sampled_D=d['cfg']['k_bc']*den/d['P0'],E2br=avg_E2(d,a,b))
    return out


def stats(d,T):
    out=window(d,0,T);S=float(np.interp(T,d['t'],d['S']));mu=lin_mom(d['t'],d['S'],0,T)[0]
    p=d['p'];l=d['l'];r=d['r'];h=d['dt_actual'];td=d['diag']['time'];i=int(np.argmin(abs(td-T)))
    require(T<=td[-1]+1e-12, 'No diagnostic support at horizon')
    exact=abs(td[i]-T)<1e-10
    if exact:
        Q=d['diag']['no_click_spin_matrix'][i]; qleft=qright=float(td[i])
    else:
        k=int(np.searchsorted(td,T)); qleft=float(td[k-1]);qright=float(td[k])
        weight=(T-qleft)/(qright-qleft)
        Q=(1-weight)*d['diag']['no_click_spin_matrix'][k-1]+weight*d['diag']['no_click_spin_matrix'][k]
    Pnc=spin_vec(Q)
    out.update(survivor_matrix_interpolated=not exact,survivor_time_left=qleft,survivor_time_right=qright,
               run_status=d['meta']['status'],complete_run=d['complete'])
    D=out['D'];M=out['M'];DE,ME=event_mom(d,0,3.6);DL=D-DE; tE=ME/DE;tL=(M-ME)/DL;wL=DL/D
    cumulative=np.r_[0,np.cumsum(p)];at_T=event_mom(d,0,T)[0]
    med=float(np.interp(.5*D,cumulative,d['t']));uncond_median=float(np.interp(.5,cumulative,d['t'])) if at_T>=.5 else np.nan
    out.update(T=T,dt=d['cfg']['dt'],Nz=d['cfg']['Nz'],Nx=d['cfg']['Nx'],Ny=d['cfg']['Ny'],S=S,mu=mu,
        survival_term=T*S,detected_moment=M,id_residual=mu-M-T*S,
        DE=DE,DL=DL,tE=tE,tL=tL,wL=wL,late_delay=wL*(tL-tE),
        Pxnc=Pnc[0],Pync=Pnc[1],Pznc=Pnc[2],conditional_median=med,unconditional_median_if_reached=uncond_median,
        conditional_moment_identity_error=out['tcond']-(tE+wL*(tL-tE)))
    cumerr=1-d['S'][1:]-np.cumsum(d['p'])
    xerr=np.r_[0,cumerr]
    expected=T*np.interp(T,d['t'],xerr)-lin_mom(d['t'],xerr,0,T)[0]
    out['id_residual_unexplained']=out['id_residual']-expected
    peak=(d['l']<3.6)&(d['r']>0);ix=np.flatnonzero(peak);j=ix[np.argmax(p[ix]/h[ix])]
    out.update(prompt_peak_g=p[j]/h[j],prompt_peak_t=(l[j]+r[j])/2)
    return out


def fit(omega,y,label,T):
    x=np.sqrt(np.asarray(omega));y=np.asarray(y);design=np.column_stack([np.ones_like(x),x]);A,B=np.linalg.lstsq(design,y,rcond=None)[0];res=y-(A+B*x)
    sse=float(res@res);sst=float(np.sum((y-y.mean())**2));n=len(y)
    return dict(label=label,T=T,omega=omega,values=y,A=A,B=B,RMS=np.sqrt(sse/n),R2=1-sse/sst,max_abs_residual=np.max(abs(res)),
        max_relative_residual_percent=100*np.max(abs(res)/abs(y)),residuals=res,n=n,residual_degrees_of_freedom=n-2,secant_slopes=np.diff(y)/np.diff(x))

